РАСКЛАДКА_2 = {"верх": (0.0, 0.0), "низ": (46.0, 145.7), "ролик": (92.5, -53.5), "фиксатор": (105.7, -7.3),
               "винт": (123.7, -94.3), "гайка": (134.5, -133.5), "ось": (25.0, -136.0)}


def flip_front_down(m):
    """Поворот на 180° вокруг вертикали профиля: передняя грань (z = ТОЛЩИНА) ложится на стол."""
    return m.rotate((0, 180, 0)).translate((0, 0, ТОЛЩИНА))


def plate_node2_lower():
    """Только нижняя часть узла 2: чтобы перепечатать её, не трогая верх, ролик и винты."""
    return lay_out([("низ", node2_lower())], {}, {"низ": seam_keepout(True)})


def plate_node2():
    upper = flip_front_down(node2_upper())
    ko_upper = (seat_keepout() + seam_keepout(False)).mirror((1, 0))
    parts = [("верх", upper), ("низ", node2_lower()), ("ролик", roller()), ("ось", pin()),
             ("фиксатор", screw(ФИКСАТОР_L)), ("винт", screw()), ("гайка", nut())]
    return lay_out(parts, РАСКЛАДКА_2, {"верх": ko_upper, "низ": seam_keepout(True)})


def write_3mf(path, parts, title):
    """parts — список (имя, Manifold, цвет '#RRGGBB' или None). Цвета нужны только картинкам."""
    colored = [(name, color) for name, _, color in parts if color]
    resources, items = [], []
    if colored:
        resources.append('<basematerials id="1">\n' + "\n".join(
            f'<base name="{name}" displaycolor="{color}"/>' for name, color in colored) + "\n</basematerials>")
    pindex = 0
    for i, (name, model, color) in enumerate(parts):
        oid = i + 2 if colored else i + 1
        mesh = model.to_mesh()
        verts = np.asarray(mesh.vert_properties)[:, :3]
        tris = np.asarray(mesh.tri_verts)
        v = "\n".join(f'<vertex x="{a:.4f}" y="{b:.4f}" z="{c:.4f}"/>' for a, b, c in verts)
        t = "\n".join(f'<triangle v1="{a}" v2="{b}" v3="{c}"/>' for a, b, c in tris)
        mat = ""
        if color:
            mat = f' pid="1" pindex="{pindex}"'
            pindex += 1
        resources.append(f'''<object id="{oid}" type="model" name="{name}"{mat}>
<mesh><vertices>
{v}
</vertices><triangles>
{t}
</triangles></mesh>
</object>''')
        items.append(f'<item objectid="{oid}"/>')
    resources_xml = "\n".join(resources)
    model_xml = f'''<?xml version="1.0" encoding="UTF-8"?>
<model unit="millimeter" xml:lang="en-US" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02">
<metadata name="Title">{title}</metadata>
<resources>
{resources_xml}
</resources>
<build>{"".join(items)}</build>
</model>'''
    ct = '''<?xml version="1.0" encoding="UTF-8"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
<Default Extension="model" ContentType="application/vnd.ms-package.3dmanufacturing-3dmodel+xml"/>
</Types>'''
    rels = '''<?xml version="1.0" encoding="UTF-8"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
<Relationship Target="/3D/3dmodel.model" Id="rel0" Type="http://schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/>
</Relationships>'''
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", ct)
        z.writestr("_rels/.rels", rels)
        z.writestr("3D/3dmodel.model", model_xml)


def report(parts, plate=False):
    for name, m, _ in parts:
        bb = m.bounding_box()
        line = (f"  {name}: объём {m.volume() / 1000:.1f} см³, кусков {len(m.decompose())}, genus {m.genus()}, "
                f"габарит {bb[3] - bb[0]:.1f} × {bb[4] - bb[1]:.1f} × {bb[5] - bb[2]:.1f}, статус {m.status()}")
        if plate:
            # подложка видна как лишняя площадь в первом слое по сравнению со вторым
            extra = m.slice(0.1).area() - m.slice(ПОДЛОЖКА_Н + 0.1).area()
            line += f", подложка {'есть' if extra > 1 else 'НЕТ'} ({extra / 100:.1f} см²)"
        print(line)


