def seam_keepout(above):
    """Плечи у шва садятся без зазора: подложку к ним не подводим. above — нижней части запрещено всё выше шва."""
    if above:
        return rect(СТОЙКА_X0 - 30, ШОВ - ПОДЛОЖКА_ОТСТУП, СТЫК_X1 + 30, СТЫК_Y1 + 30)
    return rect(СТОЙКА_X0 - 30, ШОВ - 30, СТЫК_X1 + 30, ШОВ + ПОДЛОЖКА_ОТСТУП)


