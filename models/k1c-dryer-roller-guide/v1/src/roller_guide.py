ПРОМЕЖУТОК = 2.0           # между подложками соседних деталей: подложки не сливаются
ПОЛЕ = 8.0                 # от начала координат стола до подложек

# Центры деталей в координатах профиля кронштейна. Подобраны перебором, чтобы стол был поменьше: ролик в углу
# между стойкой и плечом, гайка и винт над ним, ось слева под стойкой. Если поменять размеры и детали сойдутся
# ближе ПРОМЕЖУТКА, генератор остановится с ошибкой.
РАСКЛАДКА = {"ролик": (46.5, -38.5), "винт": (74.7, -0.3), "гайка": (34.5, 3.5), "ось": (-22.0, -122.0)}
РАСКЛАДКА_ПРОБНИКА = {"винт": (38.7, -51.3), "гайка": (34.5, -14.5)}


def lay_out(parts, places, keepouts):
    """Детали на одном столе, у каждой подложка. places — сдвиги деталей на столе, keepouts — куда подложке
    нельзя (в координатах детали до сдвига)."""
    moved = []
    for n, m in parts:
        dx, dy = places.get(n, (0.0, 0.0))
        ko = keepouts.get(n)
        moved.append((n, m.translate((dx, dy, 0)), None if ko is None else ko.translate((dx, dy))))
    outs = [pad_outline(m) for _, m, _ in moved]
    grow = [o.offset(ПРОМЕЖУТОК / 2 - 0.01, JoinType.Round) for o in outs]
    for i in range(len(moved)):
        for j in range(i + 1, len(moved)):
            if (grow[i] ^ grow[j]).area() > 1e-6:
                raise SystemExit(f"подложки «{moved[i][0]}» и «{moved[j][0]}» ближе {ПРОМЕЖУТОК} мм: поправьте раскладку")
    x0 = min(o.bounds()[0] for o in outs)
    y0 = min(o.bounds()[1] for o in outs)
    return [(n, with_pad(m, ko).translate((ПОЛЕ - x0, ПОЛЕ - y0, 0))) for n, m, ko in moved]


