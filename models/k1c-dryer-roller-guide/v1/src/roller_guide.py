def rect(x0, y0, x1, y1):
    return CrossSection.square((x1 - x0, y1 - y0)).translate((x0, y0))


def poly(pts):
    return CrossSection([pts])


def cyl_x(x0, x1, y, z, d):
    """Цилиндр вдоль X."""
    return Manifold.cylinder(x1 - x0, d / 2, d / 2, SEG).rotate((0, 90, 0)).translate((x0, y, z))


def hex_x(x0, x1, y, z, s):
    """Шестигранник вдоль X, под ключ s, вершиной вверх по печати (+Z): карман печатается без поддержек."""
    r = s / np.sqrt(3)
    pts = [(r * np.cos(np.radians(a)), r * np.sin(np.radians(a))) for a in range(0, 360, 60)]
    return Manifold.extrude(poly(pts), x1 - x0).rotate((0, 90, 0)).translate((x0, y, z))


def chamfer_pts():
    """Наружная фаска бортика: от верха (x = -ФАСКА, z = 0) до нижнего края (x = 0, z = -ФАСКА), 45°."""
    return [(0.0, -ПРОФИЛЬ_ФАСКА), (-ПРОФИЛЬ_ФАСКА, 0.0)]


def hug_chamfer():
    """Заполнение между плитой, стойкой и фаской: клипса повторяет фаску с зазором ЗАЗОР_ФАСКИ (по нормали)."""
    c = ПРОФИЛЬ_ФАСКА - ЗАЗОР_ФАСКИ * np.sqrt(2)      # линия фаски со сдвигом наружу: z = -x - c
    x_top = -c                                       # где она пересекает низ плиты (z = 0)
    z_post = -РАМА_X - c                             # и грань стойки напротив края рамы (x = РАМА_X)
    return poly([(x_top, 0.0), (РАМА_X, z_post), (РАМА_X + 0.5, z_post), (РАМА_X + 0.5, 0.0)])


def clip_profile(y_bottom):
    """Клипса на бортике и стойка до высоты y_bottom. Одна и та же у обоих узлов."""
    cs = rect(ВЫСТУП_X0, 0, СТОЙКА_X1, ПЛИТА)
    cs += rect(ВЫСТУП_X0, -ВЫСТУП_Н, ВЫСТУП_X1, 0)
    cs += hug_chamfer()
    # стойка: под фаской обходит край рамы, ниже подходит к утопленному стеклу
    cs += rect(РАМА_X, РАМА_Z, СТОЙКА_X1, ПЛИТА)
    cs += rect(СТОЙКА_X0, y_bottom, СТОЙКА_X1, РАМА_Z + 0.5)
    return cs


def arm_fork_profile(rx, rz, gap_bottom, gap_top):
    """Плечо от стойки, косынка и вилка ролика с центром (rx, rz). Устроены одинаково у обоих узлов."""
    ox0, ox1 = rx - РОЛИК_Ш / 2 - ЗАЗОР_БОК, rx + РОЛИК_Ш / 2 + ЗАЗОР_БОК
    c0, c1 = ox0 - ЩЕКА, ox1 + ЩЕКА
    oy0, oy1 = rz - РОЛИК_R - gap_bottom, rz + РОЛИК_R + gap_top
    cs = rect(СТОЙКА_X1 - 1, rz - ПЛЕЧО_Н / 2, c0 + 0.5, rz + ПЛЕЧО_Н / 2)
    # многоугольники против часовой стрелки: по часовой CrossSection считает дыркой
    cs += poly([(СТОЙКА_X1 - 0.5, rz + ПЛЕЧО_Н / 2 - 0.5), (СТОЙКА_X1 + УКОС, rz + ПЛЕЧО_Н / 2 - 0.5),
                (СТОЙКА_X1 - 0.5, rz + ПЛЕЧО_Н / 2 + УКОС)])
    cs += rect(c0, oy0 - ПЕРЕМЫЧКА, c1, oy1 + ПЕРЕМЫЧКА) - rect(ox0, oy0, ox1, oy1)
    return cs


def tilted_fork(rx, rz, gap_bottom, gap_top, tilt):
    """Вилка как у узла 1, повёрнутая в плоскости профиля на tilt градусов вокруг центра ролика (rx, rz).
    Возвращает рамку и окно: окно вырезается после того, как к рамке присоединены плечо и косынка."""
    ox = РОЛИК_Ш / 2 + ЗАЗОР_БОК
    c = ox + ЩЕКА
    oy0, oy1 = -РОЛИК_R - gap_bottom, РОЛИК_R + gap_top
    frame = rect(-c, oy0 - ПЕРЕМЫЧКА, c, oy1 + ПЕРЕМЫЧКА).rotate(tilt).translate((rx, rz))
    window = rect(-ox, oy0, ox, oy1).rotate(tilt).translate((rx, rz))
    return frame, window


def fork_local(m, rx, rz, tilt):
    """Из системы ролика (центр в нуле, ось вдоль X, середина толщины по z) на место в вилке."""
    return m.rotate((0, 0, tilt)).translate((rx, rz, 0))


def bracket_profile(y_cut=None):
    cs = clip_profile(РОЛИК_Z - ПЛЕЧО_Н / 2)
    cs += arm_fork_profile(РОЛИК_X, РОЛИК_Z, ЗАЗОР_НИЗ, ЗАЗОР_ВЕРХ)
    if y_cut is not None:
        cs = cs ^ rect(-100, y_cut, 200, 50)
    return cs


def remover_holes():
    """Отверстие под винт-съёмник и карман под его гайку со стороны стекла."""
    zc = ТОЛЩИНА / 2
    holes = cyl_x(СТОЙКА_X0 - 1, СТОЙКА_X1 + 1, ВИНТ_Z, zc, ОТВ_ВИНТА)
    holes += hex_x(СТОЙКА_X0 - 0.01, СТОЙКА_X0 + ГАЙКА_Н + КАРМАН_ЗАЗОР, ВИНТ_Z, zc, ГАЙКА_S + КАРМАН_ЗАЗОР)
    return holes


def bracket(y_cut=None):
    body = Manifold.extrude(bracket_profile(y_cut), ТОЛЩИНА)
    zc = ТОЛЩИНА / 2
    holes = remover_holes()
    if y_cut is None:
        holes += cyl_x(ОКНО_X1 - 0.5, ЩЕКА_НАР1 + 1, РОЛИК_Z, zc, ОСЬ_НАРУЖ)
        holes += cyl_x(ЩЕКА_ВН0 - 1, ОКНО_X0 + 0.5, РОЛИК_Z, zc, ОСЬ_ВНУТР)
    return body - holes


def node2_upper():
    """Верхняя часть узла 2: клипса и стойка как у узла 1, у шва стойка расширяется в блок с Т-пазом."""
    cs = clip_profile(ШОВ)
    cs += rect(СТОЙКА_X0, ШОВ, СТЫК_X1, СТЫК_Y1)
    # скос 45° от блока к стойке: без ступеньки, на которой ломается
    cs += poly([(СТОЙКА_X1 - 0.5, СТЫК_Y1 - 0.5), (СТЫК_X1, СТЫК_Y1 - 0.5), (СТОЙКА_X1 - 0.5, СТЫК_Y1 + СТЫК_X1 - СТОЙКА_X1)])
    body = Manifold.extrude(cs, ТОЛЩИНА)
    slot = rect(СТЫК_XC - Т_ГОЛОВА_Ш / 2 - Т_ЗАЗОР, ШОВ + Т_ПОЛКА, СТЫК_XC + Т_ГОЛОВА_Ш / 2 + Т_ЗАЗОР, Т_ПАЗ_Y1)
    slot += rect(СТЫК_XC - Т_ШЕЯ_Ш / 2 - Т_ЗАЗОР, ШОВ - 1, СТЫК_XC + Т_ШЕЯ_Ш / 2 + Т_ЗАЗОР, ШОВ + Т_ПОЛКА + 0.01)
    # паз открыт сзади (z = 0) и закрыт крышкой спереди
    holes = Manifold.extrude(slot, ТОЛЩИНА - Т_КРЫШКА + 1).translate((0, 0, -1))
    holes += Manifold.cylinder(Т_КРЫШКА + 2, ОТВ_ВИНТА / 2, ОТВ_ВИНТА / 2, SEG).translate(
        (СТЫК_XC, Т_ГОЛОВА_YC, ТОЛЩИНА - Т_КРЫШКА - 1))
    return body - holes - remover_holes()


def node2_lower():
    """Нижняя часть узла 2: низ узла 1 (стойка, плечо, вилка), только ролик в 40 мм от стекла. Сверху воротник
    шириной со стык и Т-головка. Плечи воротника по бокам шеи упираются в полки паза снизу."""
    a = ШОВ - ВОРОТ_Н
    cs = rect(СТОЙКА_X0, a, СТЫК_X1, ШОВ)
    cs += ccw([(СТОЙКА_X1 - 0.5, a + 0.5), (СТЫК_X1, a + 0.5), (СТОЙКА_X1 - 0.5, a + 0.5 - (СТЫК_X1 - СТОЙКА_X1))])
    cs += rect(СТОЙКА_X0, У2_РОЛИК_Z - ПЛЕЧО_Н / 2, СТОЙКА_X1, a + 0.5)
    rx, rz = У2_РОЛИК_X, У2_РОЛИК_Z
    cs += rect(СТОЙКА_X1 - 1, rz - ПЛЕЧО_Н / 2, rx, rz + ПЛЕЧО_Н / 2)
    cs += poly([(СТОЙКА_X1 - 0.5, rz + ПЛЕЧО_Н / 2 - 0.5), (СТОЙКА_X1 + УКОС, rz + ПЛЕЧО_Н / 2 - 0.5),
                (СТОЙКА_X1 - 0.5, rz + ПЛЕЧО_Н / 2 + УКОС)])
    frame, window = tilted_fork(rx, rz, У2_ЗАЗОР_НИЗ, У2_ЗАЗОР_ВЕРХ, У2_НАКЛОН)
    cs = (cs + frame) - window
    body = Manifold.extrude(cs, ТОЛЩИНА)
    tee = rect(СТЫК_XC - Т_ШЕЯ_Ш / 2, ШОВ - 0.5, СТЫК_XC + Т_ШЕЯ_Ш / 2, Т_ГОЛОВА_Y0 + 0.5)
    tee += rect(СТЫК_XC - Т_ГОЛОВА_Ш / 2, Т_ГОЛОВА_Y0, СТЫК_XC + Т_ГОЛОВА_Ш / 2, Т_ГОЛОВА_Y0 + Т_ГОЛОВА_Н)
    body += Manifold.extrude(tee, Т_ДЛИНА)
    zc = ТОЛЩИНА / 2
    # резьба под винт-фиксатор вдоль бортика, по печати вертикально; винт входит с переднего торца головки
    holes = threaded(Т_ДЛИНА + 2, ЗАЗОР_РЕЗЬБЫ).translate((СТЫК_XC, Т_ГОЛОВА_YC, -1))
    holes += Manifold.cylinder(1.0, ВИНТ_D / 2 - 0.4, ВИНТ_D / 2 + ЗАЗОР_РЕЗЬБЫ + 0.6, SEG).translate(
        (СТЫК_XC, Т_ГОЛОВА_YC, Т_ДЛИНА - 0.99))
    ox = РОЛИК_Ш / 2 + ЗАЗОР_БОК
    axle = cyl_x(ox - 0.5, ox + ЩЕКА + 1, 0, zc, ОСЬ_НАРУЖ) + cyl_x(-ox - ЩЕКА - 1, -ox + 0.5, 0, zc, ОСЬ_ВНУТР)
    holes += fork_local(axle, rx, rz, У2_НАКЛОН)
    return body - holes


def roller():
    """Ролик осью по Z, лежит на столе. Канавка с плоским дном, стенки под КАНАВКА_УГОЛ."""
    w, rb = РОЛИК_Ш, РОЛИК_ОТВ / 2
    half = КАНАВКА_ДНО / 2 + (РОЛИК_R - РОЛИК_ДНО) * np.tan(np.radians(КАНАВКА_УГОЛ))
    z1, z2 = w / 2 - half, w / 2 + half
    ch = 0.6
    pts = [(rb + ch, 0), (РОЛИК_R - ch, 0), (РОЛИК_R, ch), (РОЛИК_R, z1),
           (РОЛИК_ДНО, w / 2 - КАНАВКА_ДНО / 2), (РОЛИК_ДНО, w / 2 + КАНАВКА_ДНО / 2),
           (РОЛИК_R, z2), (РОЛИК_R, w - ch), (РОЛИК_R - ch, w), (rb + ch, w), (rb, w - ch), (rb, ch)]
    return Manifold.revolve(poly(pts), SEG)


def pin():
    """Ось ролика: шляпка на столе, стержень вверх."""
    L = ЩЕКА_НАР1 - ЩЕКА_ВН0
    head = Manifold.cylinder(ОСЬ_ШЛЯПКА_Н, ОСЬ_ШЛЯПКА_D / 2, ОСЬ_ШЛЯПКА_D / 2, SEG)
    shaft = Manifold.cylinder(L - 0.6, ОСЬ_D / 2, ОСЬ_D / 2, SEG).translate((0, 0, ОСЬ_ШЛЯПКА_Н))
    tip = Manifold.cylinder(0.6, ОСЬ_D / 2, ОСЬ_D / 2 - 0.6, SEG).translate((0, 0, ОСЬ_ШЛЯПКА_Н + L - 0.6))
    return head + shaft + tip


def thread_section(offset=0.0):
    """Сечение резьбы поперёк оси: радиус меняется по кругу треугольником, с площадками на вершине и во впадине.
    Если выдавить его с поворотом 360° на шаг, получится однозаходная резьба."""
    r_min = ВИНТ_D / 2 - ВИНТ_ГЛУБИНА
    pts = []
    for i in range(SEG):
        t = 2 * np.pi * i / SEG
        tri = 1 - abs(t / np.pi - 1)
        f = min(1.0, max(0.0, (tri - 0.12) / 0.76))
        r = r_min + ВИНТ_ГЛУБИНА * f + offset
        pts.append((r * np.cos(t), r * np.sin(t)))
    return poly(pts)


def threaded(h, offset=0.0):
    turns = h / ВИНТ_ШАГ
    return Manifold.extrude(thread_section(offset), h, int(turns * 24), 360.0 * turns)


def screw(length=ВИНТ_L):
    """Барашковый винт: барашек на столе, резьба вверх, торец плоский."""
    knob = Manifold.cylinder(БАРАШЕК_Н, БАРАШЕК_D / 2, БАРАШЕК_D / 2, SEG)
    for k in range(8):
        a = np.radians(k * 45)
        knob -= Manifold.cylinder(БАРАШЕК_Н + 2, 2.6, 2.6, 32).translate(
            (БАРАШЕК_D / 2 * np.cos(a), БАРАШЕК_D / 2 * np.sin(a), -1))
    rod = threaded(length).translate((0, 0, БАРАШЕК_Н))
    # заход резьбы и плоский торец под упор в стекло
    top = БАРАШЕК_Н + length
    lead = Manifold.cylinder(1.5, ВИНТ_D / 2 + 1, ВИНТ_D / 2 - 1.5, SEG).translate((0, 0, top - 1.5))
    keep = Manifold.cylinder(top - 1.5, 20, 20, SEG) + lead
    return (knob + rod) ^ keep


def nut_outline():
    r = ГАЙКА_S / np.sqrt(3)
    return poly([(r * np.cos(np.radians(a + 30)), r * np.sin(np.radians(a + 30))) for a in range(0, 360, 60)])


def nut():
    body = Manifold.extrude(nut_outline(), ГАЙКА_Н)
    hole = threaded(ГАЙКА_Н + 2, ЗАЗОР_РЕЗЬБЫ).translate((0, 0, -1))
    cham = Manifold.cylinder(1.0, ВИНТ_D / 2 + ЗАЗОР_РЕЗЬБЫ + 0.6, ВИНТ_D / 2 - 0.4, SEG).translate((0, 0, -0.01))
    cham += cham.mirror((0, 0, 1)).translate((0, 0, ГАЙКА_Н + 0.02))
    return body - hole - cham


def footprint(m):
    """Пятно детали на столе без дырок: подложка идёт только снаружи, в окна и отверстия не лезет."""
    outer = [p for p in m.slice(0.1).to_polygons()
             if 0.5 * np.sum(p[:, 0] * np.roll(p[:, 1], -1) - np.roll(p[:, 0], -1) * p[:, 1]) > 0]
    return CrossSection(outer)


def pad_outline(m):
    """Внешний контур детали вместе с подложкой: по нему раскладываем стол."""
    return footprint(m).offset(ПОДЛОЖКА_Ш, JoinType.Round)


def ccw(pts):
    """Многоугольник против часовой стрелки: по часовой CrossSection считает его дыркой."""
    area = 0.5 * sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(pts, pts[1:] + pts[:1]))
    return poly(pts if area > 0 else pts[::-1])


def seat_keepout():
    """Куда входит бортик принтера: под плитой между выступом и фаской, вдоль фаски и в обходе рамы.
    Клипса садится на эти грани без зазора, поэтому подложку к ним не подводим."""
    pts = [(-ПРОФИЛЬ_ПОЛОСА, 0.0), (-ПРОФИЛЬ_ФАСКА, 0.0), (0.0, -ПРОФИЛЬ_ФАСКА), (0.0, РАМА_Z - 1),
           (-ПРОФИЛЬ_ПОЛОСА, РАМА_Z - 1)]
    return ccw(pts).offset(ПОДЛОЖКА_ОТСТУП, JoinType.Round)


def with_pad(m, keepout=None):
    """Деталь для печати с подложкой: кольцо в первый слой вокруг её пятна на столе, отрывается, как кайма.
    Без подложки сопло цепляет деталь и срывает со стола: 04.11 так сорвало винт, а потом и кронштейн."""
    fp = footprint(m)
    # внутренний край чуть заходит под деталь: иначе между многоугольниками кольца и детали остаются щели-волоски
    ring = fp.offset(ПОДЛОЖКА_Ш, JoinType.Round) - fp.offset(-0.05, JoinType.Round)
    if keepout is not None:
        ring -= keepout
    return m + Manifold.extrude(ring, ПОДЛОЖКА_Н)


