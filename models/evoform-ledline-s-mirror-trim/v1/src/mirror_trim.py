"""Накладка на нижнюю кромку зеркала Evoform Ledline-S 60 × 75 (BY 2162) с полкой: закрывает сколы и трещины.

Схема автора. Пластина лежит вплотную к стеклу по всей ширине зеркала и на 3 мм выходит за его края. Она из четырёх
деталей. В крайних деталях окна под держатели полки, во всех деталях разрез под полку. Штатная стеклянная полка
ставится обратно, поверх накладки: через разрез в свои держатели, до упора.

Как держится. Деталь лежит верхней кромкой разреза на полке: полка заходит в разрез на 2 мм. За задним краем
полки остаётся перемычка, она соединяет верх и низ детали и не даёт ей уйти вперёд. Назад деталь не пускает
стекло, вбок крайние детали держатся окнами на держателях. На стекло деталь не давит, к треснувшему стеклу только
прилегает. Внизу у детали дно, оно уходит под кромку стекла: если кусок треснувшего стекла выпадет, дно его поймает.

Стыки (схема автора): на каждом стыке один прямой прямоугольный язычок и прямой паз под него, открытый в торец. Детали кладут
лицом на стол и сдвигают друг к другу вдоль шва: язычок въезжает в паз. Поднутрений нет, сдвинуть ничто не мешает.
Язычок идёт посередине толщины: спереди и сзади его не видно, спереди шов прямой. Паз закрыт спереди и со стороны
стекла, открыт только в торец, поэтому язычок держится в нём по высоте и по толщине. На печати лицом вниз язычок
висит над столом, поэтому под ним в файле печати поддержка: тонкие стенки от стола до низа язычка с зазором
в слой, после печати отламываются. Потолок паза — мост, поэтому язычок не шире 8,8 мм: мост не длиннее 10 мм.

Пластина не сплошная: лицо 2,4 мм сплошное, сзади ячейки, открытые к стеклу. Сплошные рёбра 3 мм идут по краям,
вдоль разреза (на верхнее ложится полка), вокруг окон, торцы сплошные (в них язычок или паз). Сплошная пластина
такой площади коробится на столе: большие сплошные слои сильнее тянут при остывании.

Подложки: у каждой детали кольцо в первый слой по 20 мм со всех сторон и круглые «ушки» на углах, торцы со стыками
тоже: без неё торец поднимается со стола. Остаток подложки
на торце со стыком срезать ножом, иначе шов не сойдётся. Деталь лежит на столе дальше зоны, где K1C перед печатью
чертит линию прочистки: по фото автора это буква Г у переднего левого угла стола.

Все размеры в мм. Откуда они:
  - автор, рулеткой и линейкой, 2026-11-05: ширина стекла 600; держатели 21 × 18 (ширина × высота), от бокового
    края стекла до ближнего края держателя 65, от нижней кромки до держателя 20; полка 8 × 596 × 130; полка
    до упора в держателе стоит в 5 мм от зеркала; за стеклом у кромки до коробки подсветки 3–4;
  - автор задал толщину: в разрезе 4–5, над полкой и под ней сначала 10, потом решил, что жирно, и попросил 7;
  - карточка товара: стекло 4, глубина зеркала 30, низ полос подсветки ≈113 над кромкой (чертёж похожей модели);
  - ОЦЕНКА: губки держателя по 5 мм (18 = 5 + 8 + 5), вылет держателя ≈21 (кадры видео, масштаб — рулетка);
  - ОЦЕНКА по фото печати: линия прочистки K1C у переднего левого угла, X ≈ 36…92, Y до ≈45.

Система координат сборки: X — вдоль зеркала (0 = левый край стекла), Y — к стене (лицо стекла Y = 0, комната
при Y < 0), Z — вверх (0 = нижняя кромка стекла). Для печати деталь кладётся лицом на стол.

uv run mirror_trim.py --part 1|2|3|4   -> evoform-ledline-s-mirror-trim-v1-4p-<n>.3mf: деталь с подложкой (1 — левая)
uv run mirror_trim.py --test           -> evoform-ledline-s-mirror-trim-v1-4p-test.3mf: по желанию, пробник окна и стыка
uv run mirror_trim.py --pose use       -> четыре детали в сборе, без подложек: для картинок видов
uv run mirror_trim.py --filled         -> сцена: стекло, держатели, полка, накладка; для filled.png
uv run mirror_trim.py --seam           -> стык спереди, левая отодвинута вдоль шва; для seam.png
"""
