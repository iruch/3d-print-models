ТОЛЩИНА = 7.0             # над полкой и под ней (автор): полка заходит в разрез на ТОЛЩИНА − ПОЛКА_ОТ_СТЕКЛА = 2
ПЕРЕМЫЧКА = 4.5           # в разрезе (автор: 4–5): за краем полки остаётся 0,5 мм
РАЗРЕЗ_НИЗ = 1.0          # зазор под полкой; сверху зазора нет: деталь лежит на полке
ВЕРХ = 85.0               # верх накладки над кромкой: трещины на фото поднимаются примерно до 55
СКОС = ТОЛЩИНА            # верх скошен под 45° на всю толщину: вода и пыль скатываются, на столе печатается без поддержек
ДНО_ЗАЗОР = 3.0           # дно ниже кромки стекла: запас на неточность высоты полки, дно не упрётся в кромку
ДНО_Т = 2.5               # толщина дна
ДНО_ЗА_СТЕКЛО = 2.0       # дно выходит за стекло назад: ловит выпавший кусок по всей толщине стекла
ВЫХОД_ВБОК = 3.0          # за боковой край стекла: закрыть торцы; до стен ниши 1–2 см
ОКНО_ЗАЗОР = 1.5          # окно под держатель больше него на столько с каждой стороны
ПАЗ_Ш, ПАЗ_Г = 8.0, 3.0   # паз под отвёртку к стопорному винту снизу держателя: ширина, глубина от лица.
                          # Винт примерно посередине губки (≈10 от стекла), паз даёт запас, если он ближе к стеклу

# ---------- ячейки сзади вместо сплошной пластины ----------
ЛИЦО = 2.4                # сплошное лицо: 12 слоёв по 0,2, белый PETG на просвет не покажет рёбра
РЕБРО = 1.6               # стенки ячеек: 4 периметра соплом 0,4
РАМКА = 3.0               # сплошные рёбра по краям, вдоль разреза и вокруг окон
ТОРЕЦ = 8.0               # сплошной торец: в нём зубья или гнёзда (гнездо 4,1 + стенка ≥3,9)
ШАГ_ЯЧЕЕК = 20.0          # примерный шаг рёбер вдоль детали

# ---------- стыки ----------
ЧАСТЕЙ = 4
ЗУБ_ГЛУБ = 4.0            # насколько зуб заходит в соседнюю деталь. Больше нельзя: низ под 45° от 1,5 мм за лицом
                          # доходит на конце зуба до 5,5 мм, и до задней грани (7) остаётся 1,5 мм толщины
ЗУБ_ШЕЙКА, ЗУБ_ГОЛОВА = 6.0, 9.0   # ширина зуба у шва и на конце: «ласточкин хвост» держит детали вдоль зеркала
ЗУБ_ОТ_ЛИЦА = 1.5         # зуб начинается в 1,5 мм за лицом: спереди шов прямой. Низ зуба скошен под 45° к шву
ЗУБ_ЗАЗОР = 0.1           # зазор гнезда по контуру: зуб входит туго
ГНЕЗДО_ЛИЦО = 1.3         # дно гнезда: ровное, в 1,3 мм от лица
ЗУБЬЯ_Z = (4.5, 15.5, 43.0, 57.0, 71.0)  # центры зубьев по высоте: два в нижней полосе, три в верхней

# ---------- подложки (только в файлах для печати) ----------
ПОДЛОЖКА_Ш = 20.0         # ширина кольца вокруг пятна детали на столе, со всех сторон
УШКО_R = 25.0             # круглые «ушки» на углах: углы длинной плоской детали поднимаются первыми
ПОДЛОЖКА_ПРОБНИК = 10.0   # у кусков пробника: они короткие, на столе их три
ПОДЛОЖКА_Н = 0.25         # толщина: только первый слой
ПОДЛОЖКА_ОТСТУП = 1.5     # от граней разреза и окон: верх разреза ложится на полку, в окна входят держатели
ПРОМЕЖУТОК = 2.0          # между подложками соседних деталей на столе

СТОЛ = 220.0              # стол K1C
ПРОЧИСТКА = (100.0, 55.0)  # линия прочистки у переднего левого угла (по фото): подложке нельзя в X < 100 при Y < 55
СТОЛ_Y0 = 80.0            # подложка детали начинается не ближе этого к переднему краю стола

ДЛИНА_С_ЗУБЬЯМИ = (СТЕКЛО_Ш + 2 * ВЫХОД_ВБОК + (ЧАСТЕЙ - 1) * ЗУБ_ГЛУБ) / ЧАСТЕЙ
ШОВ_1 = -ВЫХОД_ВБОК + ДЛИНА_С_ЗУБЬЯМИ - ЗУБ_ГЛУБ       # зубья левой входят во вторую
ШОВ_2 = ШОВ_1 + ДЛИНА_С_ЗУБЬЯМИ - ЗУБ_ГЛУБ             # зубья второй входят в третью
ШОВ_3 = ШОВ_2 + ДЛИНА_С_ЗУБЬЯМИ                        # зубья правой входят в третью
ГРАНИЦЫ = (-ВЫХОД_ВБОК, ШОВ_1, ШОВ_2, ШОВ_3, СТЕКЛО_Ш + ВЫХОД_ВБОК)
СТЫКИ = ((ШОВ_1, 0, 1, +1), (ШОВ_2, 1, 2, +1), (ШОВ_3, 3, 2, -1))   # шов, у кого зубья, у кого гнёзда, куда смотрят зубья
РАЗРЕЗ_Z0 = ПОЛКА_Z - РАЗРЕЗ_НИЗ
РАЗРЕЗ_Z1 = ПОЛКА_Z + ПОЛКА_Т
НИЗ = -ДНО_ЗАЗОР - ДНО_Т
ЛИЦО_ВЕРХ = ВЕРХ - СКОС   # где кончается лицо сверху, перед скосом
ДЕРЖ_X = (ДЕРЖ_ОТ_КРАЯ, ДЕРЖ_ОТ_КРАЯ + ДЕРЖ_Ш)   # левый держатель; правый — зеркально
ДЕРЖ_X_ПРАВ = (СТЕКЛО_Ш - ДЕРЖ_X[1], СТЕКЛО_Ш - ДЕРЖ_X[0])


def box(x0, x1, y0, y1, z0, z1):
    return Manifold.cube((x1 - x0, y1 - y0, z1 - z0)).translate((x0, y0, z0))


def profile():
    """Сечение детали в плоскости YZ: лицо, скос сверху, дно под кромкой стекла."""
    t = ТОЛЩИНА
    pts = [(-t, НИЗ), (СТЕКЛО_Т + ДНО_ЗА_СТЕКЛО, НИЗ), (СТЕКЛО_Т + ДНО_ЗА_СТЕКЛО, НИЗ + ДНО_Т), (0.0, НИЗ + ДНО_Т),
           (0.0, ВЕРХ), (-t, ЛИЦО_ВЕРХ)]
    return CrossSection([pts])


def extrude_x(cs, x0, x1):
    """Сечение (Y, Z) вытягивается вдоль X от x0 до x1. Extrude тянет по Z, поворот (90, 0, 90) переводит
    оси (u, v, w) сечения в (Y, Z, X)."""
    return Manifold.extrude(cs, x1 - x0).rotate((90, 0, 90)).translate((x0, 0, 0))


def holders_in(k):
    return [h for h, kk in ((ДЕРЖ_X, 0), (ДЕРЖ_X_ПРАВ, ЧАСТЕЙ - 1)) if kk == k]


def holder_cut(x0, x1):
    """Окно под держатель и паз под отвёртку снизу (к стопорному винту на нижней губке)."""
    c = ОКНО_ЗАЗОР
    w = box(x0 - c, x1 + c, -ТОЛЩИНА - 1, 1, ДЕРЖ_Z - c, ДЕРЖ_Z + ДЕРЖ_В + c)
    xm = (x0 + x1) / 2
    g = box(xm - ПАЗ_Ш / 2, xm + ПАЗ_Ш / 2, -ТОЛЩИНА - 1, -ТОЛЩИНА + ПАЗ_Г, НИЗ - 1, ДЕРЖ_Z)
    return w + g


def holder_frame(x0, x1):
    """Сплошное вокруг окна и паза: рамка РАМКА, снизу до дна."""
    c = ОКНО_ЗАЗОР + РАМКА
    return box(x0 - c, x1 + c, -ТОЛЩИНА - 1, 1, НИЗ - 1, ДЕРЖ_Z + ДЕРЖ_В + c)


def cells(x0, x1, keep):
    """Ячейки сзади: открыты к стеклу, дно — лицо ЛИЦО. Полосы по высоте между сплошными рёбрами, вдоль — шаг
    ~ШАГ_ЯЧЕЕК. keep — что оставить сплошным (торцы, рамки окон)."""
    a, b = x0 + ТОРЕЦ, x1 - ТОРЕЦ
    n = max(1, round((b - a) / ШАГ_ЯЧЕЕК))
    w = (b - a - (n - 1) * РЕБРО) / n
    mid = (РАЗРЕЗ_Z1 + РАМКА + ЛИЦО_ВЕРХ - РАМКА) / 2   # горизонтальное ребро посередине верхней полосы
    bands = [(НИЗ + РАМКА, РАЗРЕЗ_Z0 - РАМКА), (РАЗРЕЗ_Z1 + РАМКА, mid - РЕБРО / 2),
             (mid + РЕБРО / 2, ЛИЦО_ВЕРХ - РАМКА)]
    m = Manifold()
    for i in range(n):
        cx0 = a + i * (w + РЕБРО)
        for z0, z1 in bands:
            m += box(cx0, cx0 + w, -ТОЛЩИНА + ЛИЦО, 1, z0, z1)
    return m - keep


def tooth_outline(xs, d, zc, grow=0.0):
    """Контур зуба в плоскости XZ: шейка на шве xs, конец в xs ± ЗУБ_ГЛУБ (d < 0 — зуб смотрит влево).
    Шейка на 0,5 мм уходит в свою деталь, чтобы зуб сросся с ней."""
    n, h = ЗУБ_ШЕЙКА / 2, ЗУБ_ГОЛОВА / 2
    pts = [(-0.5, zc - n), (0.0, zc - n), (ЗУБ_ГЛУБ, zc - h), (ЗУБ_ГЛУБ, zc + h), (0.0, zc + n), (-0.5, zc + n)]
    if d > 0:
        pts = [(xs + x, z) for x, z in pts]
    else:
        pts = [(xs - x, z) for x, z in pts[::-1]]
    cs = CrossSection([pts])
    return cs.offset(grow, JoinType.Miter) if grow else cs


def extrude_y(cs, t):
    """Контур (X, Z) вытягивается на толщину t от задней грани (Y = 0) к лицу: Y от −t до 0."""
    return Manifold.extrude(cs, t).rotate((90, 0, 0))


def underside_45(xs, d):
    """Что срезать под зубом: всё ниже наклонной, которая идёт от шва (ЗУБ_ОТ_ЛИЦА за лицом) к концу зуба под 45°."""
    y0 = -(ТОЛЩИНА - ЗУБ_ОТ_ЛИЦА)
    pts = [(-1.0, -20.0), (20.0, -20.0), (20.0, y0 + 20.0), (0.0, y0), (-1.0, y0)]
    if d > 0:
        pts = [(xs + x, y) for x, y in pts]
    else:
        pts = [(xs - x, y) for x, y in pts[::-1]]
    return Manifold.extrude(CrossSection([pts]), 300).translate((0, 0, -100))


def teeth(xs, d):
    m = Manifold()
    for zc in ЗУБЬЯ_Z:
        m += extrude_y(tooth_outline(xs, d, zc), ТОЛЩИНА - ЗУБ_ОТ_ЛИЦА)
    return m - underside_45(xs, d)


def sockets(xs, d):
    m = Manifold()
    for zc in ЗУБЬЯ_Z:
        m += extrude_y(tooth_outline(xs, d, zc, ЗУБ_ЗАЗОР), ТОЛЩИНА - ГНЕЗДО_ЛИЦО + 1).translate((0, 1, 0))
    return m


def piece(k):
    """k = 0 … 3 слева направо."""
    x0, x1 = ГРАНИЦЫ[k], ГРАНИЦЫ[k + 1]
    m = extrude_x(profile(), x0, x1)
    m -= box(x0 - 1, x1 + 1, -ТОЛЩИНА - 1, -ПЕРЕМЫЧКА, РАЗРЕЗ_Z0, РАЗРЕЗ_Z1)   # разрез под полку
    keep = box(x0 - 1, x0 + ТОРЕЦ, -20, 20, -20, 120) + box(x1 - ТОРЕЦ, x1 + 1, -20, 20, -20, 120)
    for h in holders_in(k):
        keep += holder_frame(*h)
    m -= cells(x0, x1, keep)
    for h in holders_in(k):
        m -= holder_cut(*h)
    for xs, kt, ks, d in СТЫКИ:
        if kt == k:
            m += teeth(xs, d)
        if ks == k:
            m -= sockets(xs, d)
    return m


ИМЕНА = {1: "левая", 2: "вторая слева", 3: "вторая справа", 4: "правая"}


# ---------- печать: лицом на стол, с подложкой ----------

def to_bed(m):
    """Лицо (Y = −ТОЛЩИНА) — на стол. X остаётся вдоль стола, высота детали Z ложится в −Y стола."""
    return m.rotate((90, 0, 0)).translate((0, 0, ТОЛЩИНА))


def footprint(m):
    outer = [p for p in m.slice(0.1).to_polygons()
             if 0.5 * np.sum(p[:, 0] * np.roll(p[:, 1], -1) - np.roll(p[:, 0], -1) * p[:, 1]) > 0]
    return CrossSection(outer)


def keepout(x0, x1, holders):
    """Куда подложке нельзя (в координатах стола до сдвига): щель разреза между полосами детали, окна с пазами.
    Верхняя грань разреза ложится на полку, в окна входят держатели. За торцами подложка идёт сплошь."""
    o = ПОДЛОЖКА_ОТСТУП
    ko = CrossSection.square((x1 - x0 - 2 * o, РАЗРЕЗ_Z1 - РАЗРЕЗ_Z0 + 2 * o)).translate((x0 + o, -РАЗРЕЗ_Z1 - o))
    for a, b in holders:
        c = ОКНО_ЗАЗОР + o
        ko += CrossSection.square((b - a + 2 * c, ДЕРЖ_В + 2 * c)).translate((a - c, -(ДЕРЖ_Z + ДЕРЖ_В) - c))
        xm = (a + b) / 2
        ko += CrossSection.square((ПАЗ_Ш + 2 * o, ДЕРЖ_Z - НИЗ + 2 * o)).translate((xm - ПАЗ_Ш / 2 - o, -ДЕРЖ_Z - o))
    return ko


def pad(m, ko, width, ears):
    """Кольцо в первый слой вокруг пятна детали; ушки — круги на углах прямоугольника пятна."""
    fp = footprint(m)
    outer = fp.offset(width, JoinType.Round)
    if ears:
        b = fp.bounds()
        for cx in (b[0], b[2]):
            for cy in (b[1], b[3]):
                outer += CrossSection.circle(ears, 64).translate((cx, cy))
    ring = outer - fp.offset(-0.05, JoinType.Round) - ko
    return Manifold.extrude(ring, ПОДЛОЖКА_Н)


def place(parts, y0=СТОЛ_Y0):
    """Детали (уже с подложками) в ряд вдоль X с промежутком, ряд по центру по X, по Y от y0. Проверка стола и
    зоны прочистки."""
    xs = []
    total = 0.0
    for _, m in parts:
        bb = m.bounding_box()
        xs.append(bb)
        total += bb[3] - bb[0]
    total += ПРОМЕЖУТОК * (len(parts) - 1)
    x = (СТОЛ - total) / 2
    out = []
    for (n, m), bb in zip(parts, xs):
        mm = m.translate((x - bb[0], y0 - bb[1], 0))
        x += bb[3] - bb[0] + ПРОМЕЖУТОК
        b = mm.bounding_box()
        if b[0] < 0.5 or b[1] < 0.5 or b[3] > СТОЛ - 0.5 or b[4] > СТОЛ - 0.5:
            raise SystemExit(f"«{n}» с подложкой не помещается на стол: {[round(v, 1) for v in b]}")
        if b[0] < ПРОЧИСТКА[0] and b[1] < ПРОЧИСТКА[1]:
            raise SystemExit(f"«{n}» заходит в зону линии прочистки: {[round(v, 1) for v in b]}")
        out.append((n, mm))
    return out


def plate(k):
    x0, x1 = ГРАНИЦЫ[k], ГРАНИЦЫ[k + 1]
    m = to_bed(piece(k))
    m = m + pad(m, keepout(x0, x1, holders_in(k)), ПОДЛОЖКА_Ш, УШКО_R)
    return place([(ИМЕНА[k + 1], m)])


def test_plate():
    """Пробник: кусок левой детали с окном (примерить на держатель и пропустить полку через разрез) и пара кусков
    со стыком: конец левой с зубьями и начало второй с гнёздами."""
    clip = lambda a, b: box(a, b, -50, 50, -50, 150)
    w0, w1 = ДЕРЖ_X[0] - ОКНО_ЗАЗОР - РАМКА - 8, ДЕРЖ_X[1] + ОКНО_ЗАЗОР + РАМКА + 8   # окно с рамкой и по 8 мм
    pieces = [("окно", piece(0) ^ clip(w0, w1), (w0, w1), holders_in(0)),
              ("зубья", piece(0) ^ clip(ШОВ_1 - 16.0, ШОВ_1 + ЗУБ_ГЛУБ + 1), (ШОВ_1 - 16.0, ШОВ_1), []),
              ("гнёзда", piece(1) ^ clip(ШОВ_1, ШОВ_1 + 16.0), (ШОВ_1, ШОВ_1 + 16.0), [])]
    out = []
    for n, m, (a, b), hs in pieces:
        mb = to_bed(m)
        out.append((n, mb + pad(mb, keepout(a, b, hs), ПОДЛОЖКА_ПРОБНИК, 0)))
    return place(out)


# ---------- сцена для картинки с содержимым ----------

def glass():
    """Стекло со сколом слева и ступенькой справа (по фото, грубо: только для картинки)."""
    w = СТЕКЛО_Ш
    pts = [(0, 200), (0, 6), (12, 4), (22, 8), (30, 3), (36, 0), (w - 100, 0), (w - 80, 6), (w - 52, 6),
           (w - 30, 8), (w - 30, 20), (w - 6, 20), (w, 26), (w, 200)]
    cs = CrossSection([pts[::-1]])
    if cs.area() <= 0:
        cs = CrossSection([pts])
    return Manifold.extrude(cs, СТЕКЛО_Т).rotate((90, 0, 0)).translate((0, СТЕКЛО_Т, 0))


def holder(x0):
    x1 = x0 + ДЕРЖ_Ш
    z0, g, s = ДЕРЖ_Z, ДЕРЖ_ГУБКА, ПОЛКА_Т
    return (box(x0, x1, -ПОЛКА_ОТ_СТЕКЛА, 0, z0, z0 + ДЕРЖ_В) + box(x0, x1, -ДЕРЖ_ВЫЛЕТ, 0, z0, z0 + g)
            + box(x0, x1, -ДЕРЖ_ВЫЛЕТ, 0, z0 + g + s, z0 + ДЕРЖ_В))


def shelf():
    xs = (СТЕКЛО_Ш - ПОЛКА_Д) / 2
    return box(xs, xs + ПОЛКА_Д, -ПОЛКА_ОТ_СТЕКЛА - ПОЛКА_Г, -ПОЛКА_ОТ_СТЕКЛА, ПОЛКА_Z, ПОЛКА_Z + ПОЛКА_Т)


def scene():
    parts = [("стена", box(-40, СТЕКЛО_Ш + 40, ДО_СТЕНЫ, ДО_СТЕНЫ + 8, -90, 230), "#f4ece1"),
             ("зеркало", glass(), "#e2f0f4"),
             ("подсветка", box(ПОДСВЕТКА_X[0], ПОДСВЕТКА_X[1], -0.4, 0, ПОДСВЕТКА_Z, 200)
              + box(СТЕКЛО_Ш - ПОДСВЕТКА_X[1], СТЕКЛО_Ш - ПОДСВЕТКА_X[0], -0.4, 0, ПОДСВЕТКА_Z, 200), "#fffbe8"),
             ("держатели", holder(ДЕРЖ_X[0]) + holder(ДЕРЖ_X_ПРАВ[0]), "#cfd5da"),
             ("полка", shelf(), "#c6dcd6")]
    parts += [(f"накладка, {ИМЕНА[k + 1]}", piece(k), None) for k in range(ЧАСТЕЙ)]
    # камера картинки смотрит сверху под ~44°: наклоняем сцену, чтобы зеркало было видно почти в лоб
    return [(n, m.rotate((-30, 0, 0)).rotate((0, 0, -20)), c) for n, m, c in parts]


def seam_scene():
    """Стык левой и второй со стороны стекла: левая приподнята над гнёздами, чтобы видно зубья."""
    clip = box(ШОВ_1 - 50, ШОВ_1 + 50, -50, 50, -50, 120)
    left = (piece(0) ^ clip).translate((0, 14, 0))
    mid = piece(1) ^ clip
    parts = [("левая", left, "#9fc3e6"), ("вторая", mid, "#f1e3b5")]
    return [(n, m.translate((-ШОВ_1, 0, -40)).rotate((0, 0, 180)).rotate((-25, 0, 0)).rotate((0, 0, -25)), c)
            for n, m, c in parts]


# ---------- 3mf ----------

def write_3mf(path, parts, title):
    """parts — список (имя, Manifold, цвет '#RRGGBB' или None). Цвета нужны только картинкам."""
    colored = [(name, color) for name, _, color in parts if color]
    resources, items = [], []
    if colored:
        resources.append('<basematerials id="1">\n' + "\n".join(
            f'<base name="{name}" displaycolor="{color}"/>' for name, color in colored) + "\n</basematerials>")
    pindex = 0
    for i, (name, model, color) in enumerate(parts):
        oid = i + 2 if colored else i + 1
        mesh = model.to_mesh()
        verts = np.asarray(mesh.vert_properties)[:, :3]
        tris = np.asarray(mesh.tri_verts)
        v = "\n".join(f'<vertex x="{a:.4f}" y="{b:.4f}" z="{c:.4f}"/>' for a, b, c in verts)
        t = "\n".join(f'<triangle v1="{a}" v2="{b}" v3="{c}"/>' for a, b, c in tris)
        mat = ""
        if color:
            mat = f' pid="1" pindex="{pindex}"'
            pindex += 1
        resources.append(f'<object id="{oid}" type="model" name="{name}"{mat}>\n<mesh><vertices>\n{v}\n'
                         f'</vertices><triangles>\n{t}\n</triangles></mesh>\n</object>')
        items.append(f'<item objectid="{oid}"/>')
    model_xml = ('<?xml version="1.0" encoding="UTF-8"?>\n<model unit="millimeter" xml:lang="en-US" '
                 'xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02">\n'
                 f'<metadata name="Title">{title}</metadata>\n<resources>\n' + "\n".join(resources)
                 + f'\n</resources>\n<build>{"".join(items)}</build>\n</model>')
    ct = ('<?xml version="1.0" encoding="UTF-8"?>\n<Types xmlns="http://schemas.openxmlformats.org/package/2006/'
          'content-types">\n<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.'
          'relationships+xml"/>\n<Default Extension="model" ContentType="application/vnd.ms-package.'
          '3dmanufacturing-3dmodel+xml"/>\n</Types>')
    rels = ('<?xml version="1.0" encoding="UTF-8"?>\n<Relationships xmlns="http://schemas.openxmlformats.org/'
            'package/2006/relationships">\n<Relationship Target="/3D/3dmodel.model" Id="rel0" Type="http://'
            'schemas.microsoft.com/3dmanufacturing/2013/01/3dmodel"/>\n</Relationships>')
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", ct)
        z.writestr("_rels/.rels", rels)
        z.writestr("3D/3dmodel.model", model_xml)


def report(parts, plate=False):
    for name, m, _ in parts:
        bb = m.bounding_box()
        line = (f"  {name}: объём {m.volume() / 1000:.1f} см³, кусков {len(m.decompose())}, genus {m.genus()}, "
                f"габарит {bb[3] - bb[0]:.1f} × {bb[4] - bb[1]:.1f} × {bb[5] - bb[2]:.1f}, статус {m.status()}")
        if plate:
            extra = m.slice(0.1).area() - m.slice(ПОДЛОЖКА_Н + 0.1).area()
            line += f", подложка {'есть' if extra > 1 else 'НЕТ'} ({extra / 100:.1f} см²)"
            line += f", на столе x {bb[0]:.1f}…{bb[3]:.1f}, y {bb[1]:.1f}…{bb[4]:.1f}"
        print(line)


